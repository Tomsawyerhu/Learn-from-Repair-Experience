#!/usr/bin/env python3
"""
Multi-Turn Vulnerability Repair Runner

Automated script that aggregates the multi-turn vulnerability repair workflow:
1. patcheval_exp.py - vulnerability repair
2. pipeline.py - experience generation and indexing
3. aggregate_statistics.py - statistical analysis

Usage:
    # Run 5 turns with the default retrieve-only mode (with experience injection)
    python multi_turn_runner.py -n 5 -o output

    # Run all turns in baseline mode (no experience injection)
    # Note: baseline mode automatically generates a cold-start experience DB for turn_1
    # and stores it under turn_1/cold-start/vec_DB
    python multi_turn_runner.py -n 5 -o output --run-mode baseline

    # Run retrieve-only mode using the cold-start experience DB generated by baseline
    python multi_turn_runner.py -n 5 -o output_with_exp \
        --exp-db /path/to/baseline_output/turn_1/cold-start/vec_DB

    # Full example
    python multi_turn_runner.py \
        -d /path/to/dataset.jsonl \
        -o /path/to/output \
        -n 5 \
        --run-mode retrieve-only \
        --filter-turns 1 \
        --workers 32 \
        --eval-workers 32
"""

import argparse
import json
import logging
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, Optional, List, Tuple

import yaml

# Project root directory (this script is located at the root)
PROJECT_ROOT = Path(__file__).resolve().parent
MINISWEAGENT_ROOT = PROJECT_ROOT / "minisweagent"
EXPBANK_ROOT = PROJECT_ROOT / "expbank"

# Configure logging
logging.basicConfig(
    level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s", handlers=[logging.StreamHandler()]
)
logger = logging.getLogger(__name__)


class MultiTurnRunner:
    """
    Multi-turn vulnerability repair runner.

    Integrates repair, experience generation, and statistical analysis.
    """

    def __init__(
        self,
        dataset_path: str,
        output_dir: str,
        num_turns: Optional[int] = 5,
        filter_turns: int = 1,
        model: str = "dashscope/deepseek-v3.2",
        model_class: str = "litellm_tool",
        workers: int = 32,
        eval_workers: int = 32,
        docker_timeout: int = 600,
        exp_retrieve_k: int = 10,
        exp_return_n: int = 3,
        exp_db_path: Optional[str] = None,
        exp_model_path: Optional[str] = None,
        pipeline_config: Optional[str] = None,
        patcheval_config: Optional[str] = None,
        run_mode: str = "retrieve-only",
        comment: Optional[str] = None,
        skip_existing_turns: bool = True,
        auto_eval: bool = True,
        dry_run: bool = False,
        start_turn: Optional[int] = None,
        auto_stop_on_no_new_fixes: bool = True,
        early_stop: bool = True,
        exp_success_check: Optional[int] = None,
    ):
        """
        Initialize the multi-turn runner.

        Args:
            dataset_path: Dataset file path (.jsonl)
            output_dir: Base output directory
            num_turns: Number of turns (None or 0 means auto-run until no new fixed CVEs)
            filter_turns: Enable filtering for the first N turns (exclude current CVE + temporal filter)
            model: Model to use
            model_class: Model class
            workers: Parallel worker count (default: 32)
            eval_workers: Evaluation worker count (default: 32)
            docker_timeout: Docker timeout
            exp_retrieve_k: Number of retrieved experiences
            exp_return_n: Number of returned experiences
            exp_db_path: Experience DB path (default: expbank/src/vec_DB)
            exp_model_path: BGE model path (default: expbank/models/bge-large-en-v1.5)
            pipeline_config: Pipeline config path (default: expbank/src/config/run/pipeline_config.yaml)
            patcheval_config: patcheval_exp.py config path (default: minisweagent/config/extra/patcheval_exp.yaml)
            run_mode: Run mode (baseline/retrieve-only)
            comment: Run note to save in output_dir/info.txt
            skip_existing_turns: Whether to skip existing turns
            auto_eval: Whether to auto-evaluate
            dry_run: Validate config only
            start_turn: Start from turn N (default: None, auto-detect)
            auto_stop_on_no_new_fixes: When num_turns is None, stop automatically if no new fixed CVEs (default: True)
            early_stop: Even with fixed turns, stop when no new fixed CVEs (early-stop strategy, default: True)
            exp_success_check: Expected number of successful experiences in DB; abort on mismatch (default: None, disabled)
        """
        self.dataset_path = Path(dataset_path).resolve()
        self.output_dir = Path(output_dir).resolve()
        self.num_turns = num_turns if num_turns and num_turns > 0 else None
        self.is_auto_run = self.num_turns is None
        self.filter_turns = filter_turns
        self.model = model
        self.model_class = model_class
        self.workers = workers
        self.eval_workers = eval_workers
        self.docker_timeout = docker_timeout
        self.exp_retrieve_k = exp_retrieve_k
        self.exp_return_n = exp_return_n
        self.exp_db_path = Path(exp_db_path) if exp_db_path else EXPBANK_ROOT / "src" / "vec_DB"
        self.exp_model_path = Path(exp_model_path) if exp_model_path else EXPBANK_ROOT / "models" / "bge-large-en-v1.5"
        self.pipeline_config = (
            Path(pipeline_config)
            if pipeline_config
            else EXPBANK_ROOT / "src" / "config" / "run" / "pipeline_config.yaml"
        )
        self.patcheval_config = Path(patcheval_config) if patcheval_config else None
        self.run_mode = run_mode
        self.comment = comment
        self.skip_existing_turns = skip_existing_turns
        self.auto_eval = auto_eval
        self.dry_run = dry_run
        self.start_turn = start_turn
        self.auto_stop_on_no_new_fixes = auto_stop_on_no_new_fixes
        self.early_stop = early_stop
        self.exp_success_check = exp_success_check

        # Run statistics
        self.run_stats: Dict[str, Any] = {
            "started_at": None,
            "completed_at": None,
            "turns": {},
            "config": {},
            "auto_run": self.is_auto_run,
            "early_stop": self.early_stop,
            "actual_turns": 0,
        }

        # Log file
        self.log_file: Optional[Path] = None

    def _setup_logging(self):
        """Set up log file."""
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.log_file = self.output_dir / f"multi_turn_run_{datetime.now().strftime('%Y%m%d_%H%M%S')}.log"

        file_handler = logging.FileHandler(self.log_file, encoding="utf-8")
        file_handler.setFormatter(logging.Formatter("%(asctime)s - %(levelname)s - %(message)s"))
        logger.addHandler(file_handler)

        logger.info(f"Log file: {self.log_file}")

    def _save_info_file(self):
        """Save run note to info.txt."""
        info_file = self.output_dir / "info.txt"

        info_lines = [
            f"Run time: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            f"Run type: {'Auto run (stop when no new fixed CVEs)' if self.is_auto_run else f'Fixed turns ({self.num_turns} turns)'}",
            f"Run strategy: {self.run_mode}",
            f"Model: {self.model}",
        ]

        if self.comment:
            info_lines.append("")
            info_lines.append("Note:")
            info_lines.append(self.comment)

        with open(info_file, "w", encoding="utf-8") as f:
            f.write("\n".join(info_lines))

        logger.info(f"Run info saved: {info_file}")

    def _validate_config(self) -> bool:
        """Validate configuration."""
        errors = []

        if not self.dataset_path.exists():
            errors.append(f"Dataset file does not exist: {self.dataset_path}")

        if not self.exp_model_path.exists():
            errors.append(f"BGE model path does not exist: {self.exp_model_path}")

        if not self.pipeline_config.exists():
            errors.append(f"Pipeline config file does not exist: {self.pipeline_config}")

        # Validate run_mode
        valid_modes = ["baseline", "retrieve-only"]
        if self.run_mode not in valid_modes:
            errors.append(f"Invalid run_mode: {self.run_mode}, valid values: {', '.join(valid_modes)}")

        # Check required scripts
        patcheval_script = MINISWEAGENT_ROOT / "run" / "extra" / "patcheval_exp.py"
        if not patcheval_script.exists():
            errors.append(f"patcheval_exp.py does not exist: {patcheval_script}")

        pipeline_script = EXPBANK_ROOT / "src" / "pipeline.py"
        if not pipeline_script.exists():
            errors.append(f"pipeline.py does not exist: {pipeline_script}")

        aggregate_script = MINISWEAGENT_ROOT / "run" / "extra" / "aggregate_statistics.py"
        if not aggregate_script.exists():
            errors.append(f"aggregate_statistics.py does not exist: {aggregate_script}")

        if errors:
            for err in errors:
                logger.error(f"Configuration error: {err}")
            return False

        logger.info("Configuration validation passed")
        return True

    def _setup_output_experience_db(self) -> bool:
        """
        Set up the experience DB under the output directory.

        Logic:
        1. If run_mode is baseline, skip DB setup.
        2. Check whether {output_dir}/vec_DB exists.
        3. If not, copy from the path specified by --exp-db.
        4. If --exp-success-check is set, validate the successful experience count.
        5. Update self.exp_db_path = {output_dir}/vec_DB.

        Returns:
            True if setup succeeds, False otherwise
        """
        if self.run_mode == "baseline":
            logger.info("Baseline mode, skipping experience DB setup")
            return True

        target_db = self.output_dir / "vec_DB"
        initial_exp_db = self.exp_db_path

        if target_db.exists():
            logger.info(f"Experience DB already exists in output directory: {target_db}")
            logger.info("Skipping copy and using existing DB directly")
        else:
            if not initial_exp_db.exists():
                logger.error(f"Initial experience DB does not exist: {initial_exp_db}")
                return False

            logger.info("Starting to copy initial experience DB...")
            logger.info(f"Source path: {initial_exp_db}")
            logger.info(f"Target path: {target_db}")

            target_db.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(initial_exp_db, target_db)

            logger.info("Experience DB copy completed")

        self.exp_db_path = target_db
        logger.info(f"Current experience DB path: {self.exp_db_path}")

        if self.exp_success_check is not None:
            logger.info("Validating successful experience count in DB...")
            stats = self._get_experience_db_stats()
            actual_success = stats.get("success", 0)

            logger.info(f"Expected successful experiences: {self.exp_success_check}")
            logger.info(f"Actual successful experiences: {actual_success}")

            if actual_success != self.exp_success_check:
                logger.error(
                    f"Successful experience count validation failed: expected {self.exp_success_check}, actual {actual_success}"
                )
                return False

            logger.info("Successful experience count validation passed")

        return True

    def _clean_dry_run_files(self) -> bool:
        """
        Check and clean config/result files created by previous dry runs.

        If a previous run was dry_run mode, remove config and result files
        so they can be replaced by the new non-dry-run config.

        Returns:
            True if files are cleaned or no action needed, False otherwise
        """
        config_file = self.output_dir / "multi_turn_config.json"
        result_file = self.output_dir / "multi_turn_result.json"

        cleaned = False

        # Check whether the result file is marked as dry_run
        if result_file.exists():
            try:
                with open(result_file, "r", encoding="utf-8") as f:
                    result = json.load(f)

                if result.get("statistics", {}).get("dry_run", False):
                    logger.info("Detected a previous dry_run execution")
                    if config_file.exists():
                        logger.info(f"Deleting {config_file}")
                        config_file.unlink()
                    logger.info(f"Deleting {result_file}")
                    result_file.unlink()
                    cleaned = True
                else:
                    logger.info("Detected a previous real run config, keeping existing config file")
            except Exception as e:
                logger.warning(f"Failed to read result file, skipping cleanup: {e}")

        if cleaned:
            logger.info("Dry_run file cleanup complete, new config will be used")

        return True

    def _get_experience_db_stats(self) -> Dict[str, Any]:
        """
        Get statistics from the experience DB.

        Returns:
            A stats dict including:
            - total: total experience count
            - success: successful experience count
            - fail: failed experience count
            - unknown: unknown status count
        """
        stats = {"total": 0, "success": 0, "fail": 0, "unknown": 0}

        if not self.exp_db_path.exists():
            logger.info("Experience DB directory does not exist, returning empty stats")
            return stats

        try:
            import chromadb
            from chromadb.config import Settings

            # Connect to the experience DB
            client = chromadb.PersistentClient(
                path=str(self.exp_db_path), settings=Settings(anonymized_telemetry=False)
            )

            # Get collection
            try:
                collection = client.get_collection("cwe_experiences")
            except Exception:
                logger.info("Experience DB collection does not exist, returning empty stats")
                return stats

            # Get metadata of all records
            all_records = collection.get(include=["metadatas"])

            if all_records and all_records["metadatas"]:
                stats["total"] = len(all_records["metadatas"])

                for metadata in all_records["metadatas"]:
                    repair_result = metadata.get("repair_result", "unknown")
                    if repair_result == "success":
                        stats["success"] += 1
                    elif repair_result == "fail":
                        stats["fail"] += 1
                    else:
                        stats["unknown"] += 1

            logger.info(
                f"Experience DB stats: total={stats['total']}, success={stats['success']}, fail={stats['fail']}"
            )

        except ImportError:
            logger.warning("chromadb is not installed; cannot collect DB statistics")
        except Exception as e:
            logger.warning(f"Error while collecting DB statistics: {e}")

        return stats

    def _get_run_mode_for_turn(self, turn_num: int) -> str:
        """
        Determine the final run mode based on config and turn number.

        Args:
            turn_num: Turn number (1-based)

        Returns:
            Final run mode: baseline or retrieve-only
        """
        return self.run_mode

    def _run_repair_turn(self, turn_num: int) -> Dict[str, Any]:
        """
        Run one repair turn.

        Args:
            turn_num: Turn number (1-based)

        Returns:
            Turn run result
        """
        logger.info("=" * 60)
        logger.info(f"Starting repair for turn {turn_num}")
        logger.info("=" * 60)

        turn_start = time.time()

        # Decide whether to enable filtering
        use_filter = turn_num <= self.filter_turns

        # Get run mode
        run_mode = self._get_run_mode_for_turn(turn_num)

        # Build command
        cmd = [
            sys.executable,
            str(MINISWEAGENT_ROOT / "run" / "extra" / "patcheval_exp.py"),
            "-d",
            str(self.dataset_path),
            "-o",
            str(self.output_dir),
            "-w",
            str(self.workers),
            "--model",
            self.model,
            "--model-class",
            self.model_class,
            "--mode",
            run_mode,
            "--exp-db",
            str(self.exp_db_path),
            "--exp-model",
            str(self.exp_model_path),
            "--exp-retrieve-k",
            str(self.exp_retrieve_k),
            "--exp-return-n",
            str(self.exp_return_n),
            "--docker-timeout",
            str(self.docker_timeout),
            "--eval-workers",
            str(self.eval_workers),
        ]

        # Config file (if specified)
        if self.patcheval_config:
            cmd.extend(["--config", str(self.patcheval_config)])

        # Filtering options (only valid for non-baseline mode)
        if run_mode != "baseline":
            if use_filter:
                # Enable filtering: exclude current CVE + temporal filter
                cmd.append("--temporal-filter")
                # --exclude-current-cve is the default and does not need to be added explicitly
                logger.info(f"Filtering enabled for turn {turn_num} (exclude current CVE + temporal filter)")
            else:
                # Do not enable filtering
                cmd.append("--no-exclude-current-cve")
                logger.info(f"Filtering disabled for turn {turn_num} (allow using same-CVE experience)")
        else:
            logger.info(f"Turn {turn_num} is baseline mode, no experience injection")

        # Auto evaluation
        if self.auto_eval:
            cmd.append("--auto-eval")

        logger.info(f"Run command: {' '.join(cmd)}")

        if self.dry_run:
            logger.info("[DRY RUN] Skip actual execution")
            return {"success": True, "dry_run": True, "duration": 0}

        result = subprocess.run(
            cmd,
            cwd=str(PROJECT_ROOT),
            capture_output=False,  # Directly print to terminal
            text=True,
        )

        turn_duration = time.time() - turn_start

        if result.returncode != 0:
            logger.error(f"Repair failed on turn {turn_num} (exit code: {result.returncode})")
            return {"success": False, "exit_code": result.returncode, "duration": turn_duration}

        logger.info(f"Repair completed for turn {turn_num}, duration: {turn_duration:.2f}s")

        return {"success": True, "duration": turn_duration, "use_filter": use_filter, "run_mode": run_mode}

    def _get_pipeline_output_dir(self) -> Path:
        """
        Get the pipeline output directory.

        Based on output.base_dir in pipeline_config.yaml and the last path segment of -o.
        Example: -o ./output/gpt-5-mini-0 -> base_dir/gpt-5-mini-0/

        Returns:
            Full path to the pipeline output directory
        """
        # Read pipeline config file
        try:
            with open(self.pipeline_config, "r", encoding="utf-8") as f:
                config = yaml.safe_load(f)
            base_dir = config.get("output", {}).get("base_dir", "./src/artifact/")
        except Exception as e:
            logger.warning(f"Unable to read pipeline config file, using default base_dir: {e}")
            base_dir = "./src/artifact/"

        # Convert relative path to absolute path (relative to EXPBANK_ROOT)
        base_dir_path = Path(base_dir)
        if not base_dir_path.is_absolute():
            base_dir_path = EXPBANK_ROOT / base_dir_path

        # Get the last segment of output_dir
        experiment_name = self.output_dir.name

        # Build full output path
        pipeline_output = base_dir_path / experiment_name

        return pipeline_output

    def _run_experience_pipeline(self, turn_num: int, db_dir: Optional[Path] = None) -> Dict[str, Any]:
        """
        Run the experience generation pipeline.

        Args:
            turn_num: Turn number (1-based)
            db_dir: Experience DB output directory (default: self.exp_db_path)

        Returns:
            Pipeline run result
        """
        logger.info("-" * 40)
        logger.info(f"Generating experiences for turn {turn_num}...")
        logger.info("-" * 40)

        # Locate the current turn directory
        turn_dir = self.output_dir / f"turn_{turn_num}"

        # Get pipeline output directory (configured base_dir + experiment name)
        pipeline_output_dir = self._get_pipeline_output_dir()
        logger.info(f"Pipeline intermediate output directory: {pipeline_output_dir}")

        # Use specified db_dir or default value
        target_db_dir = db_dir if db_dir else self.exp_db_path

        # Build command
        cmd = [
            sys.executable,
            "-m",
            "src.pipeline",
            "--config",
            str(self.pipeline_config),
            "--input-dir",
            str(turn_dir),
            "--output-dir",
            str(pipeline_output_dir),
            "--db-dir",
            str(target_db_dir),
            "--workers",
            "32",
        ]

        logger.info(f"Run command: {' '.join(cmd)}")

        if self.dry_run:
            logger.info("[DRY RUN] Skip actual execution")
            return {"success": True, "dry_run": True}

        # Check whether directory exists only during real execution
        if not turn_dir.exists():
            logger.error(f"Turn directory does not exist: {turn_dir}")
            return {"success": False, "error": f"Turn directory not found: {turn_dir}"}

        result = subprocess.run(cmd, cwd=str(EXPBANK_ROOT), capture_output=True, text=True)

        if result.returncode != 0:
            logger.error(f"Experience generation failed: {result.stderr}")
            return {"success": False, "error": result.stderr}

        logger.info(f"Experience generation completed:\n{result.stdout[-500:] if len(result.stdout) > 500 else result.stdout}")

        return {"success": True, "output": result.stdout}

    def _run_cold_start_experience_generation(self) -> Dict[str, Any]:
        """
        Generate cold-start experience DB for turn_1 in baseline mode.

        Store experience under turn_1/cold-start/vec_DB for later runs with experience DB.

        Returns:
            Experience generation result
        """
        logger.info("=" * 60)
        logger.info("Generating cold-start experience DB (Baseline Turn 1)...")
        logger.info("=" * 60)

        # Cold-start experience DB path
        cold_start_db_dir = self.output_dir / "turn_1" / "cold-start" / "vec_DB"

        logger.info(f"Cold-start experience DB path: {cold_start_db_dir}")

        # Run experience pipeline and write output to cold-start directory
        result = self._run_experience_pipeline(turn_num=1, db_dir=cold_start_db_dir)

        if result.get("success"):
            logger.info(f"Cold-start experience DB generation completed: {cold_start_db_dir}")
            logger.info("Subsequent runs can use this path via --exp-db")
        else:
            logger.warning("Cold-start experience DB generation failed")

        return result

    def _run_aggregate_statistics(self) -> Dict[str, Any]:
        """Run statistical analysis."""
        logger.info("=" * 60)
        logger.info("Generating statistics report...")
        logger.info("=" * 60)

        cmd = [
            sys.executable,
            str(MINISWEAGENT_ROOT / "run" / "extra" / "aggregate_statistics.py"),
            str(self.output_dir),
        ]

        # Add input.json path for language-mapping fallback
        input_json = EXPBANK_ROOT / "datasets" / "input.json"
        if input_json.exists():
            cmd.extend(["--input-json", str(input_json)])

        logger.info(f"Run command: {' '.join(cmd)}")

        if self.dry_run:
            logger.info("[DRY RUN] Skip actual execution")
            return {"success": True, "dry_run": True}

        result = subprocess.run(cmd, cwd=str(PROJECT_ROOT), capture_output=True, text=True)

        if result.returncode != 0:
            logger.error(f"Statistics analysis failed: {result.stderr}")
            return {"success": False, "error": result.stderr}

        logger.info(f"Statistics analysis completed:\n{result.stdout}")

        return {"success": True, "output": result.stdout}

    def _get_turn_status(self) -> Tuple[List[int], List[int], List[int]]:
        """
        Get status of all turns.

        Returns:
            (completed, incomplete, all_turns):
            - completed: Turns with complete evaluation results (has summary.json)
            - incomplete: Existing but incomplete turns (no summary.json)
            - all_turns: All existing turn directories
        """
        completed = []
        incomplete = []
        all_turns = []

        if self.output_dir.exists():
            for d in self.output_dir.iterdir():
                if d.is_dir() and d.name.startswith("turn_"):
                    try:
                        turn_num = int(d.name.split("_")[1])
                        all_turns.append(turn_num)

                        # Check whether evaluation result exists
                        summary_file = d / "evaluation" / "summary.json"
                        if summary_file.exists():
                            completed.append(turn_num)
                        else:
                            incomplete.append(turn_num)
                    except ValueError:
                        continue

        return sorted(completed), sorted(incomplete), sorted(all_turns)

    def _get_existing_turns(self) -> List[int]:
        """Get completed turns (backward compatibility)."""
        completed, _, _ = self._get_turn_status()
        return completed

    def _get_new_strict_fixed_cves(self, turn_num: int) -> int:
        """
        Get number of newly strictly-fixed CVEs in this turn.

        Compare this turn with all previous turn evaluations to compute newly strictly-fixed CVEs.

        Args:
            turn_num: Turn number (1-based)

        Returns:
            Number of newly strictly-fixed CVEs in this turn
        """
        # Collect strictly-fixed CVEs from all previous turns
        all_previous_fixed_cves: set = set()

        for t in range(1, turn_num):
            turn_dir = self.output_dir / f"turn_{t}"
            summary_path = turn_dir / "evaluation" / "summary.json"
            if summary_path.exists():
                try:
                    with open(summary_path, "r", encoding="utf-8") as f:
                        data = json.load(f)
                    strict_eval = data.get("strict_evaluation", {})
                    successful_cves_dict = strict_eval.get("successful_cves", {})
                    if isinstance(successful_cves_dict, dict):
                        for lang, cve_list in successful_cves_dict.items():
                            if isinstance(cve_list, list):
                                all_previous_fixed_cves.update(cve_list)
                except Exception as e:
                    logger.debug(f"Error reading evaluation result for turn {t}: {e}")

        # Get strictly-fixed CVEs in this turn
        current_turn_fixed_cves: set = set()
        turn_dir = self.output_dir / f"turn_{turn_num}"
        summary_path = turn_dir / "evaluation" / "summary.json"
        if summary_path.exists():
            try:
                with open(summary_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                strict_eval = data.get("strict_evaluation", {})
                successful_cves_dict = strict_eval.get("successful_cves", {})
                if isinstance(successful_cves_dict, dict):
                    for lang, cve_list in successful_cves_dict.items():
                        if isinstance(cve_list, list):
                            current_turn_fixed_cves.update(cve_list)
            except Exception as e:
                logger.warning(f"Error reading evaluation result for turn {turn_num}: {e}")

        # Compute count of new CVEs
        new_fixed_count = len(current_turn_fixed_cves - all_previous_fixed_cves)

        logger.info(
            f"Strictly-fixed CVEs in turn {turn_num}: {len(current_turn_fixed_cves)}, newly fixed: {new_fixed_count}"
        )

        return new_fixed_count

    def _calculate_exp_generation_cost(self, turn_num: int) -> float:
        """
        Calculate experience generation cost for the specified turn.

        Read all JSON files under artifact/.../exp_json and sum their cost fields.

        Args:
            turn_num: Turn number (1-based)

        Returns:
            Total experience generation cost for this turn
        """
        pipeline_output_dir = self._get_pipeline_output_dir()
        exp_json_base = pipeline_output_dir / f"turn_{turn_num}" / "exp_json"

        if not exp_json_base.exists():
            logger.debug(f"Experience JSON directory does not exist: {exp_json_base}")
            return 0.0

        total_exp_cost = 0.0
        json_files_found = 0

        for json_file in exp_json_base.rglob("*.json"):
            try:
                with open(json_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                cost = data.get("cost")
                if cost is not None:
                    total_exp_cost += float(cost)
                    json_files_found += 1
            except Exception as e:
                logger.debug(f"Error reading experience JSON file {json_file}: {e}")
                continue

        logger.debug(f"Experience generation cost for turn {turn_num}: ${total_exp_cost:.4f} (from {json_files_found} files)")
        return total_exp_cost

    def _update_cumulative_repair_counts(self) -> bool:
        """
        Update cumulative repair count and cost files.

        Read summary.json and raw_traj data from all completed turns, accumulate repair counts and costs,
        then write results to txt/csv/json files under output_dir.
        """
        results_txt = []
        results_csv = [
            "Turn,Fixed_In_Turn,New_Fixed,Cumulative_Fixed,Turn_Cost,Cumulative_Cost,Exp_Cost,Cumulative_Exp_Cost,Total_Cost,Cumulative_Total_Cost"
        ]
        results_json = []

        cumulative_fixed_cves = set()
        cumulative_cost = 0.0
        cumulative_exp_cost = 0.0
        cumulative_total_cost = 0.0

        completed, incomplete, all_turns = self._get_turn_status()

        if not completed:
            logger.info("No completed turns yet, skipping cumulative metrics update")
            return False

        for turn_num in sorted(completed):
            turn_dir = self.output_dir / f"turn_{turn_num}"
            summary_path = turn_dir / "evaluation" / "summary.json"
            raw_traj_dir = turn_dir / "raw_traj"

            current_turn_fixed = set()

            if summary_path.exists():
                try:
                    with open(summary_path, "r", encoding="utf-8") as f:
                        data = json.load(f)

                    strict_eval = data.get("strict_evaluation", {})
                    successful_cves_dict = strict_eval.get("successful_cves", {})

                    if isinstance(successful_cves_dict, dict):
                        for lang, cve_list in successful_cves_dict.items():
                            if isinstance(cve_list, list):
                                current_turn_fixed.update(cve_list)

                except Exception as e:
                    logger.warning(f"Error reading {summary_path}: {e}")
            else:
                logger.warning(f"Evaluation result not found for turn {turn_num}: {summary_path}")

            turn_cost = 0.0
            if raw_traj_dir.exists():
                for traj_file in raw_traj_dir.rglob("*.traj.json"):
                    try:
                        with open(traj_file, "r", encoding="utf-8") as f:
                            data = json.load(f)
                        stats = data.get("info", {}).get("model_stats", {})
                        if not stats:
                            stats = data.get("model_stats", {})
                        cost = stats.get("instance_cost")
                        if cost is not None:
                            turn_cost += float(cost)
                    except Exception:
                        continue

            exp_cost = self._calculate_exp_generation_cost(turn_num)
            turn_total_cost = turn_cost + exp_cost

            original_count = len(cumulative_fixed_cves)
            cumulative_fixed_cves.update(current_turn_fixed)
            new_count = len(cumulative_fixed_cves)
            added = new_count - original_count

            cumulative_cost += turn_cost
            cumulative_exp_cost += exp_cost
            cumulative_total_cost += turn_total_cost

            logger.info(
                f"Turn {turn_num}: fixed {len(current_turn_fixed)} (new: {added}). Cumulative fixed: {new_count}. "
                f"Repair cost: ${turn_cost:.2f} (cumulative: ${cumulative_cost:.2f}). "
                f"Experience cost: ${exp_cost:.2f} (cumulative: ${cumulative_exp_cost:.2f}). "
                f"Total cost: ${turn_total_cost:.2f} (cumulative: ${cumulative_total_cost:.2f})"
            )

            results_txt.append(
                f"Turn {turn_num}: Cumulative_Fixed={new_count}, Cumulative_Repair_Cost=${cumulative_cost:.2f}, "
                f"Cumulative_Exp_Cost=${cumulative_exp_cost:.2f}, Cumulative_Total_Cost=${cumulative_total_cost:.2f}"
            )
            results_csv.append(
                f"{turn_num},{len(current_turn_fixed)},{added},{new_count},{turn_cost:.4f},{cumulative_cost:.4f},"
                f"{exp_cost:.4f},{cumulative_exp_cost:.4f},{turn_total_cost:.4f},{cumulative_total_cost:.4f}"
            )
            results_json.append(
                {
                    "turn": turn_num,
                    "fixed_in_turn": len(current_turn_fixed),
                    "new_fixed": added,
                    "cumulative_fixed": new_count,
                    "turn_cost": round(turn_cost, 4),
                    "cumulative_cost": round(cumulative_cost, 4),
                    "exp_cost": round(exp_cost, 4),
                    "cumulative_exp_cost": round(cumulative_exp_cost, 4),
                    "turn_total_cost": round(turn_total_cost, 4),
                    "cumulative_total_cost": round(cumulative_total_cost, 4),
                }
            )

        txt_file = self.output_dir / "cumulative_metrics.txt"
        csv_file = self.output_dir / "cumulative_metrics.csv"
        json_file = self.output_dir / "cumulative_metrics.json"

        try:
            with open(txt_file, "w", encoding="utf-8") as f:
                f.write("\n".join(results_txt) + "\n")
            with open(csv_file, "w", encoding="utf-8") as f:
                f.write("\n".join(results_csv) + "\n")
            with open(json_file, "w", encoding="utf-8") as f:
                json.dump(results_json, f, indent=2)
            logger.info(f"Cumulative metrics updated: txt/csv/json files are in {self.output_dir}")
            return True
        except Exception as e:
            logger.error(f"Failed to write cumulative metric files: {e}")
            return False

    def _clean_turns(self, turns: List[int]):
        """Clean specified turn directories."""
        for turn_num in turns:
            turn_dir = self.output_dir / f"turn_{turn_num}"
            if turn_dir.exists():
                logger.info(f"Cleaning incomplete turn: turn_{turn_num}")
                shutil.rmtree(turn_dir)

    def _determine_start_turn(self) -> int:
        """
        Determine the start turn.

        Logic:
        1. If start_turn is specified, use it.
        2. Otherwise, find the last completed turn and continue from the next one.
        3. Automatically clean incomplete directories from the start turn onward.

        Returns:
            Start turn number
        """
        completed, incomplete, all_turns = self._get_turn_status()

        # Print current status
        if all_turns:
            logger.info(f"Detected turn directories: {all_turns}")
            if completed:
                logger.info(f"  ✓ Completed (has summary.json): {completed}")
            if incomplete:
                logger.info(f"  ✗ Incomplete (no summary.json): {incomplete}")

        # Determine start turn
        if hasattr(self, "start_turn") and self.start_turn is not None:
            start = self.start_turn
            logger.info(f"Using specified start turn: {start}")
            # When start turn is specified, clean all directories from that turn onward (including completed turns)
            turns_to_clean = [t for t in all_turns if t >= start]
        elif self.skip_existing_turns and completed:
            start = max(completed) + 1
            logger.info(f"Continuing after last completed turn {max(completed)}")
            # In auto-detect mode, only clean incomplete directories
            turns_to_clean = [t for t in incomplete if t >= start]
        else:
            start = 1
            logger.info("Starting from turn 1")
            turns_to_clean = [t for t in all_turns if t >= start]

        # Execute cleanup
        if turns_to_clean:
            if self.dry_run:
                logger.info(f"[DRY RUN] Would clean turn directories: {turns_to_clean}")
            else:
                logger.info(f"Cleaning turn directories: {turns_to_clean}")
                self._clean_turns(turns_to_clean)

        return start

    def _save_run_config(self):
        """Save run configuration."""
        # Get initial experience DB statistics
        initial_exp_stats = self._get_experience_db_stats()

        config = {
            "dataset_path": str(self.dataset_path),
            "output_dir": str(self.output_dir),
            "auto_run": self.is_auto_run,
            "num_turns": "auto" if self.is_auto_run else self.num_turns,
            "auto_stop_on_no_new_fixes": self.auto_stop_on_no_new_fixes if self.is_auto_run else None,
            "filter_turns": self.filter_turns,
            "model": self.model,
            "model_class": self.model_class,
            "workers": self.workers,
            "eval_workers": self.eval_workers,
            "exp_retrieve_k": self.exp_retrieve_k,
            "exp_return_n": self.exp_return_n,
            "exp_db_path": str(self.exp_db_path),
            "run_mode": self.run_mode,
            "auto_eval": self.auto_eval,
            "started_at": datetime.now().isoformat(),
            "initial_experience_stats": initial_exp_stats,
        }

        self.run_stats["config"] = config

        config_file = self.output_dir / "multi_turn_config.json"
        with open(config_file, "w", encoding="utf-8") as f:
            json.dump(config, f, indent=2, ensure_ascii=False)

        logger.info(f"Run config saved: {config_file}")

    def run(self) -> Dict[str, Any]:
        """
        Run the complete multi-turn repair workflow.

        When num_turns is None, auto-run until no new fixed CVEs are found.
        When early_stop=True, stop early even in fixed-turn mode if no new fixed CVEs are found.

        Returns:
            Run result statistics
        """
        self._setup_logging()

        logger.info("=" * 70)
        logger.info("Starting multi-turn vulnerability repair workflow")
        if self.is_auto_run:
            logger.info("Auto-run mode: run until no new fixed CVEs are found")
        else:
            logger.info(f"Fixed-turn mode: will run for {self.num_turns} turns")
            if self.early_stop:
                logger.info("Early-stop strategy: enabled (stop when no new fixed CVEs)")
            else:
                logger.info("Early-stop strategy: disabled (run all specified turns)")
        logger.info("=" * 70)

        self.run_stats["started_at"] = datetime.now().isoformat()

        # Validate configuration
        if not self._validate_config():
            return {"success": False, "error": "Configuration validation failed"}

        # Clean previous dry_run files
        self._clean_dry_run_files()

        # Set up experience DB under output directory
        if not self._setup_output_experience_db():
            return {"success": False, "error": "Experience database setup failed"}

        # Save run information (note)
        self._save_info_file()

        # Determine start turn (automatically cleans incomplete turn directories)
        start_turn = self._determine_start_turn()

        if self.is_auto_run:
            logger.info(f"Will start from turn {start_turn}, auto-run until no new fixed CVEs are found")
        else:
            if self.early_stop:
                logger.info(
                    f"Will start from turn {start_turn}, run until turn {self.num_turns} or until no new fixed CVEs"
                )
            else:
                logger.info(f"Will start from turn {start_turn} and run through turn {self.num_turns}")

        # Save run configuration (including DB statistics before first turn)
        self._save_run_config()

        # Run each turn
        turn_num = start_turn
        max_turns = 1000 if self.is_auto_run else self.num_turns  # Reasonable cap in auto mode to avoid infinite loops

        while turn_num <= max_turns:
            turn_stats = {"turn_num": turn_num}

            # Record DB state before this turn starts
            exp_stats_before = self._get_experience_db_stats()
            turn_stats["experience_db_before"] = exp_stats_before
            logger.info(
                f"Experience DB state before turn {turn_num}: "
                f"total={exp_stats_before['total']}, "
                f"success={exp_stats_before['success']}, "
                f"fail={exp_stats_before['fail']}"
            )

            # Repair
            repair_result = self._run_repair_turn(turn_num)
            turn_stats["repair"] = repair_result

            if not repair_result.get("success"):
                logger.error(f"Repair failed on turn {turn_num}, terminating run")
                self.run_stats["turns"][f"turn_{turn_num}"] = turn_stats
                break

            # Update cumulative repair metric files
            self._update_cumulative_repair_counts()

            # Experience generation (baseline mode only generates cold-start experience on turn_1)
            new_strict_fixed_cves = 0  # Number of newly strictly-fixed CVEs in this turn

            if self.run_mode != "baseline":
                pipeline_result = self._run_experience_pipeline(turn_num)
                turn_stats["pipeline"] = pipeline_result

                if not pipeline_result.get("success"):
                    logger.warning(f"Experience generation failed on turn {turn_num}, continuing to next turn")
                else:
                    # Record DB state after experience generation
                    exp_stats_after = self._get_experience_db_stats()
                    turn_stats["experience_db_after"] = exp_stats_after
                    # Calculate newly added experiences
                    new_total = exp_stats_after["total"] - exp_stats_before["total"]
                    new_success_exp = exp_stats_after["success"] - exp_stats_before["success"]
                    new_fail = exp_stats_after["fail"] - exp_stats_before["fail"]
                    logger.info(
                        f"After experience generation for turn {turn_num}: "
                        f"total={exp_stats_after['total']} (+{new_total}), "
                        f"success={exp_stats_after['success']} (+{new_success_exp}), "
                        f"fail={exp_stats_after['fail']} (+{new_fail})"
                    )

                    # Get strictly-fixed CVEs for this turn (from evaluation results)
                    new_strict_fixed_cves = self._get_new_strict_fixed_cves(turn_num)
                    turn_stats["new_strict_fixed_cves"] = new_strict_fixed_cves

                    # Check whether to stop
                    should_stop = False
                    stop_reason = None

                    # Check in auto-run mode
                    if self.is_auto_run and self.auto_stop_on_no_new_fixes:
                        if new_strict_fixed_cves == 0:
                            should_stop = True
                            stop_reason = "Auto mode: number of newly strictly-fixed CVEs is zero"

                    # In fixed-turn mode, check early stop
                    elif not self.is_auto_run and self.early_stop:
                        if new_strict_fixed_cves == 0:
                            should_stop = True
                            stop_reason = "Early-stop strategy: number of newly strictly-fixed CVEs is zero"

                    if should_stop:
                        logger.info(f"Turn {turn_num}: {stop_reason}. Stopping run")
                        self.run_stats["turns"][f"turn_{turn_num}"] = turn_stats
                        turn_num += 1  # Update actual number of executed turns
                        break

            elif turn_num == 1:
                # In baseline mode, generate cold-start experience DB after turn_1 finishes
                cold_start_result = self._run_cold_start_experience_generation()
                turn_stats["cold_start_pipeline"] = cold_start_result
            else:
                logger.info(f"Baseline mode, skipping experience generation for turn {turn_num}")

            self.run_stats["turns"][f"turn_{turn_num}"] = turn_stats
            turn_num += 1

            # In fixed-turn mode, check whether upper bound has been reached
            if not self.is_auto_run and turn_num > self.num_turns:
                break

        # Record actual number of executed turns
        self.run_stats["actual_turns"] = turn_num - start_turn

        # Statistical analysis
        stats_result = self._run_aggregate_statistics()
        self.run_stats["statistics"] = stats_result

        self.run_stats["completed_at"] = datetime.now().isoformat()

        # Save run result
        result_file = self.output_dir / "multi_turn_result.json"
        with open(result_file, "w", encoding="utf-8") as f:
            json.dump(self.run_stats, f, indent=2, ensure_ascii=False)

        logger.info("=" * 70)
        logger.info("Multi-turn vulnerability repair workflow completed")
        if self.is_auto_run or self.early_stop:
            logger.info(f"Actual executed turns: {self.run_stats['actual_turns']}")
        logger.info(f"Result saved to: {result_file}")
        logger.info(f"Statistics report: {self.output_dir / 'statistics'}")
        logger.info("=" * 70)

        return self.run_stats


