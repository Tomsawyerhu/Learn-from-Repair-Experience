    parser.add_argument("--model-class", default="litellm_tool", help="Model class")

    # Parallelism configuration
    parser.add_argument("-w", "--workers", type=int, default=32, help="Repair parallel worker count (default: 32)")
    parser.add_argument("--eval-workers", type=int, default=32, help="Evaluation parallel worker count (default: 32)")
    parser.add_argument("--docker-timeout", type=int, default=600, help="Docker timeout in seconds (default: 600)")

